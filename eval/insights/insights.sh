#!/usr/bin/env bash
# Post-run INSIGHTS step: deterministic extractor + transcript condenser for one run, then
# prints the command to launch the (paid) analysis agent. Never launches an agent itself.
#
#   eval/insights/insights.sh <run-id> [--runs-dir DIR] [--out DIR] [--repo DIR] [--budget N]
#                                      [--agent auto|codex|claude|cursor|opencode] [--usage-csv FILE]
#
# Outputs (default runs/<run-id>/insights/): stats.json, digest.md, analysis-prompt.md
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HARNESS_ROOT="$(cd "$HERE/../.." && pwd)"

usage() { sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }
[[ $# -ge 1 ]] || usage 2
[[ "$1" == "-h" || "$1" == "--help" ]] && usage 0
RUN_ID="$1"; shift

RUNS_DIR="${RUNS_DIR:-$HARNESS_ROOT/runs}"
OUT=""; REPO=""; BUDGET="${INSIGHTS_BUDGET:-150000}"; AGENT=""; USAGE_CSV=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --runs-dir) RUNS_DIR="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --repo) REPO="$2"; shift 2 ;;
    --budget) BUDGET="$2"; shift 2 ;;
    --agent) AGENT="$2"; shift 2 ;;
    --usage-csv) USAGE_CSV="$2"; shift 2 ;;
    -h|--help) usage 0 ;;
    *) echo "unknown option: $1" >&2; usage 2 ;;
  esac
done

RUN="$RUNS_DIR/$RUN_ID"
[[ -d "$RUN" ]] || { echo "run dir not found: $RUN" >&2; exit 1; }
OUT="${OUT:-$RUN/insights}"
REPO="${REPO:-$RUN/workspace}"
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
command -v node >/dev/null || { echo "node is required (>= 18)" >&2; exit 1; }

# Exact-value redaction: every secret value the harness or the run knows about.
SECRETS=()
for f in "$HARNESS_ROOT/.env" "$HARNESS_ROOT/secrets.env" "$RUN/workspace/.env" "$RUN/workspace/.env.local"; do
  [[ -f "$f" ]] && SECRETS+=(--secrets-file "$f")
done
EXTRA=()
[[ -n "$AGENT" ]] && EXTRA+=(--agent "$AGENT")
[[ -n "$USAGE_CSV" ]] && EXTRA+=(--usage-csv "$USAGE_CSV")

echo "== extract  -> $OUT/stats.json" >&2
node "$HERE/extract.mjs" --run-dir "$RUN" --repo "$REPO" --out "$OUT/stats.json" ${SECRETS[@]+"${SECRETS[@]}"} ${EXTRA[@]+"${EXTRA[@]}"}
echo "== condense -> $OUT/digest.md (budget $BUDGET chars)" >&2
node "$HERE/condense.mjs" --run-dir "$RUN" --budget "$BUDGET" --out "$OUT/digest.md" ${SECRETS[@]+"${SECRETS[@]}"} ${AGENT:+--agent "$AGENT"}

# The analyst reads the working tree: it must be at the run's final commit.
HEAD_STATS="$(node -e 'const s=require(process.argv[1]); process.stdout.write((s.git&&s.git.head)||"")' "$OUT/stats.json")"
HEAD_WT="$(git -C "$REPO" rev-parse HEAD 2>/dev/null || true)"
if [[ -n "$HEAD_STATS" && "$HEAD_WT" != "$HEAD_STATS" ]]; then
  echo "WARNING: $REPO is checked out at ${HEAD_WT:-?}, but the run head is $HEAD_STATS." >&2
  echo "         The analyst would read the wrong code. Use a checkout of the run head (e.g. git worktree/clone) via --repo." >&2
fi

# Render the analysis prompt with absolute paths.
REPO_ABS="$(cd "$REPO" 2>/dev/null && pwd || echo "$REPO")"
BASE="$(node -e 'const s=require(process.argv[1]); process.stdout.write((s.git&&s.git.base)||"unknown")' "$OUT/stats.json")"
sed -e "s#{{RUN_ID}}#$RUN_ID#g" -e "s#{{STATS}}#$OUT/stats.json#g" -e "s#{{DIGEST}}#$OUT/digest.md#g" \
    -e "s#{{REPO}}#$REPO_ABS#g" -e "s#{{OUT}}#$OUT#g" -e "s#{{BASE}}#$BASE#g" -e "s#{{SCHEMA}}#$HERE/insights.schema.json#g" \
    "$HERE/insights-prompt.md" > "$OUT/analysis-prompt.md"

# The exact analysis command, as a script (executed by ./oneshotshop evaluate; also runnable by
# hand). The prompt goes in on STDIN: --allowedTools/--disallowedTools are variadic and would
# swallow a trailing positional prompt. Extra claude flags can be passed as arguments.
{
  printf '#!/usr/bin/env bash\n# Generated by eval/insights/insights.sh — insights analysis (paid, host claude).\n'
  printf '# Usage: bash analysis-cmd.sh [extra claude flags, e.g. --output-format json --max-budget-usd 10]\n'
  printf 'set -euo pipefail\ncd %q\n' "$OUT"
  # shellcheck disable=SC2016  # literal $vars for the generated script
  printf 'exec "${CLAUDE_BIN:-claude}" -p --model sonnet "$@" \\\n'
  printf '  --add-dir %q \\\n' "$REPO_ABS"
  printf '  --allowedTools Read Grep Glob Write Edit %q %q \\\n' "Bash(git -C $REPO_ABS log:*)" "Bash(git -C $REPO_ABS show:*)"
  printf '  --disallowedTools %q %q \\\n' "Write(/$REPO_ABS/**)" "Edit(/$REPO_ABS/**)"
  printf '  < analysis-prompt.md\n'
} > "$OUT/analysis-cmd.sh"
chmod +x "$OUT/analysis-cmd.sh"

cat <<EOF

Done. Inputs for the analyst are in $OUT
  stats.json          deterministic numbers ($(wc -c < "$OUT/stats.json" | tr -d ' ') bytes)
  digest.md           condensed, redacted transcript ($(wc -c < "$OUT/digest.md" | tr -d ' ') bytes)
  analysis-prompt.md  rendered prompt

Review digest.md before sharing it anywhere. To run the analysis agent (paid, on the host):

  bash "$OUT/analysis-cmd.sh"

  (prompt on stdin; see the file for the exact claude flags)

Then check the result:

  node "$HERE/check-insights.mjs" "$OUT"
EOF
